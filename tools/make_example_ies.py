"""Write the synthetic example photometry in examples/ies/.

These are smooth analytic distributions for trying `nocturne bug` and
`nocturne trespass`, not measurements of any product. For procurement, use
the manufacturer's LM-63 file for the exact catalogue number.

    python tools/make_example_ies.py
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from vdl7.photometry import synthetic, write_ies  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "examples", "ies")
EXAMPLES = [
    ("synthetic-roadway-6000lm-u0.ies", synthetic("roadway", 6000, watts=45),
     "Asymmetric roadway optic, nothing above 85 deg", 45),
    ("synthetic-globe-4000lm-ulr15.ies", synthetic("globe", 4000, ulr=0.15, watts=40),
     "Post-top globe, clear refractor, 15 % of flux upward", 40),
    ("synthetic-globe-4000lm-reflector-u0.ies", synthetic("globe", 4000, ulr=0.0, watts=40),
     "Post-top globe with an internal top reflector, no uplight", 40),
]


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    for name, phot, desc, watts in EXAMPLES:
        text = write_ies(phot, {"TEST": "SYNTHETIC EXAMPLE - NOT A PRODUCT", "MANUFAC": "Nocturne examples",
                                "LUMINAIRE": desc, "OTHER": "Generated by tools/make_example_ies.py"}, watts=watts)
        with open(os.path.join(OUT, name), "w") as f:
            f.write(text)
        print(f"{name:42s} {phot.bug()}  ULR {phot.ulr:.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
